// Generates src/ParamTable.inc from the web UI's own parameter table (DEF in js/saraswati.js),
// so plugin parameter ranges and defaults can never drift from the browser version.
//   node tools/gen_param_table.mjs > src/ParamTable.inc
import { loadDefs } from '../tests/js_engine.mjs';

const { DEF } = loadDefs();
const rows = Object.values(DEF).map((d) =>
  `    { "${d.id}", ${d.min}, ${d.max}, ${d.def}, ${d.int ? 'true' : 'false'}, ${d.log ? 'true' : 'false'} },`);
console.log('// Generated by tools/gen_param_table.mjs from js/saraswati.js — do not edit by hand.');
console.log('// { id, min, max, default, integer, logarithmic }');
console.log(rows.join('\n'));
